    /// <summary>
    /// Emits the data type table, which Discovery does not carry.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The generator has always read <c>data-types.json</c> and used none of it, so a consumer
    /// needing "does steps support get" had to copy the table into their own application — which
    /// one did, from this repository, with a comment saying it had nowhere else to get it.
    /// </para>
    /// <para>
    /// <strong>Metadata, not validation.</strong> The snapshot says capabilities "must not become
    /// client-side hard validation; the server remains the authority", so nothing in the SDK reads
    /// this before sending. It answers a question; it does not stop a request.
    /// </para>
    /// <para>
    /// <c>FilterName</c> is published and filter expressions are not built from it. The table has
    /// the member's prefix and no more: <c>heart-rate</c> filters on
    /// <c>heart_rate.sample_time.physical_time</c> while <c>steps</c> filters on
    /// <c>steps.interval.start_time</c>, and three types reject the interval member the others
    /// accept. Composing an expression from the prefix would produce a 400 that looks like the
    /// SDK's own answer.
    /// </para>
    /// </remarks>
    private GeneratedFile EmitDataTypes()
    {
        var writer = Header(RootNamespace);

        writer.XmlDoc("summary", "A data type, and the operations Google documents for it.");
        writer.XmlDoc(
            "remarks",
            "Metadata only. The service is the authority on what a type supports; this is what its "
            + "own documentation says, captured when the contract was generated.");

        using (writer.Block("public sealed record HealthDataDataTypeDescriptor"))
        {
            writer.XmlDoc("summary", "The kebab-case id used in a resource name, for example `heart-rate`.");
            writer.Line("public required string Id { get; init; }");
            writer.Line();

            writer.XmlDoc("summary", "The snake_case name a filter is written against, for example `heart_rate`.");
            writer.XmlDoc(
                "remarks",
                "A different string from the id and not derivable from it - both are preserved "
                + "verbatim. It is the prefix of a filter member, not a filter: the rest of the path "
                + "differs per type, and some types accept no filter at all. Build an expression "
                + "from what the service documents for the type, not from this.");
            writer.Line("public required string FilterName { get; init; }");
            writer.Line();

            writer.XmlDoc("summary", "The operation short names documented for this type, for example `list`.");
            writer.Line("public required IReadOnlyList<string> Operations { get; init; }");
            writer.Line();

            writer.XmlDoc("summary", "Whether the documentation lists an operation for this type.");
            writer.XmlDoc(
                "remarks",
                "Worth asking before offering a button, and not worth refusing a request over: a "
                + "type that gained an operation after this contract was generated answers false "
                + "here and succeeds at the service.");
            writer.Line("public bool Supports(string operation)");
            writer.Line("    => Operations.Contains(operation, StringComparer.Ordinal);");
        }

        writer.Line();
        writer.XmlDoc("summary", "The data types the Google Health API documents.");
        writer.XmlDoc(
            "remarks",
            "Captured from https://developers.google.com/health/data-types, which is the only place "
            + "this appears: the REST path is the generic dataTypes/{dataTypesId}, so Discovery says "
            + "nothing about what any individual type supports.");

        using (writer.Block("public static class HealthDataGeneratedDataTypes"))
        {
            writer.XmlDoc("summary", "Every documented data type, ordered by id.");
            writer.Line("public static IReadOnlyList<HealthDataDataTypeDescriptor> All { get; } =");
            writer.Line("[");

            foreach (var dataType in contract.DataTypes)
            {
                var operations = string.Join(", ", dataType.Operations.Select(CodeWriter.Literal));

                writer.Line("    new()");
                writer.Line("    {");
                writer.Line($"        Id = {CodeWriter.Literal(dataType.Id)},");
                writer.Line($"        FilterName = {CodeWriter.Literal(dataType.FilterName)},");
                writer.Line($"        Operations = [{operations}],");
                writer.Line("    },");
            }

            writer.Line("];");
            writer.Line();

            writer.XmlDoc("summary", "The descriptor for an id, or null when the id is not documented here.");
            writer.XmlDoc(
                "remarks",
                "Null is not the same as unsupported. A type Google adds after this contract was "
                + "generated is absent from the table and works perfectly well at the service.");
            writer.Line("public static HealthDataDataTypeDescriptor? Find(string id)");
            writer.Line("    => All.FirstOrDefault(dataType => string.Equals(dataType.Id, id, StringComparison.Ordinal));");
        }

        return new GeneratedFile("Generated/Api/HealthDataGeneratedDataTypes.g.cs", writer.ToString());
    }

    /// <summary>
    /// Emits the alternatives of each union, for the check that runs before a request is written.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The same member list <c>GetKind</c> is generated from, in a form the serializer can read.
    /// Discovery cannot say "exactly one of these", so nothing in the type system stops two being
    /// set; the service refuses it and says which operation failed rather than which pair did.
    /// </para>
    /// <para>
    /// Wire names, because that is what the write contract's properties are keyed by, and what the
    /// message should quote — a caller reading it is about to go and look at the JSON.
    /// </para>
    /// </remarks>
    private GeneratedFile EmitUnionMembers()
    {
        var writer = Header(RootNamespace + ".Serialization", ModelsNamespace);

        writer.XmlDoc("summary", "The mutually exclusive members of each union schema, keyed by model type.");
        writer.XmlDoc(
            "remarks",
            "Used to refuse a request that sets two of them. Members that are not alternatives - "
            + "dataSource, which every measurement carries - are not listed, exactly as they are "
            + "left out of GetKind.");

        using (writer.Block("public static class HealthDataUnionMembers"))
        {
            writer.XmlDoc("summary", "Wire property names that are alternatives, keyed by model type.");

            using (writer.Block(
                "public static readonly IReadOnlyDictionary<Type, string[]> ByType = new Dictionary<Type, string[]>",
                closing: "};"))
            {
                foreach (var (unionSchema, declared) in _unions.OrderBy(u => u.Key, StringComparer.Ordinal))
                {
                    if (contract.Schemas.SingleOrDefault(s => s.WireName == unionSchema) is not { } schema)
                    {
                        continue;
                    }

                    var names = schema.Properties
                        .Where(p => p.Type.Kind == TypeKind.Reference)
                        .Where(p => !declared.ExcludedMembers.Contains(p.WireName))
                        .Select(p => CodeWriter.Literal(p.WireName));

                    writer.Line($"[typeof({schema.CSharpName})] = [{string.Join(", ", names)}],");
                }
            }
        }

        return new GeneratedFile("Generated/Serialization/HealthDataUnionMembers.g.cs", writer.ToString());
    }

    /// <summary>
    /// Emits discovery helpers for a union-shaped schema.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <c>DataPoint</c> is a name plus 42 mutually exclusive measurement members, and
    /// <c>RollupDataPoint</c> is the same shape with 21. Working with that as bare nullable
    /// properties means writing a 42-arm if-chain at every call site. These helpers give the
    /// caller the populated member without collapsing the union into <c>object</c>.
    /// </para>
    /// <para>
    /// Not every message-typed property is an alternative. <c>DataPoint.dataSource</c> records
    /// which device or app produced the measurement and is present alongside it, so counting it
    /// as a member made <c>GetKind</c> answer <c>DataSource</c> for everything the service
    /// actually returns. Which ones to leave out is declared in <c>semantics.json</c>, never
    /// inferred from the schema, because the schema does not say.
    /// </para>
    /// </remarks>
    private GeneratedFile EmitUnionHelpers(SchemaContract schema, IReadOnlySet<string> excludedMembers)
    {
        var members = schema.Properties
            .Where(p => p.Type.Kind == TypeKind.Reference)
            .Where(p => !excludedMembers.Contains(p.WireName))
            .ToArray();

        var kindEnum = $"{schema.CSharpName}Kind";
        var writer = Header(ModelsNamespace);

        writer.XmlDoc("summary", $"Which member of a {schema.CSharpName} carries a value.");
        writer.XmlDoc(
            "remarks",
            "Unknown means the service sent a member added after this contract was generated. " +
            "That is not an error: the payload still round-trips, it simply has no typed accessor here.");

        using (writer.Block($"public enum {kindEnum}"))
        {
            writer.XmlDoc("summary", "No measurement member was set.");
            writer.Line("None,");
            writer.Line();
            writer.XmlDoc("summary", "A member this contract does not know about was set.");
            writer.Line("Unknown,");

            foreach (var member in members)
            {
                writer.Line();
                writer.XmlDoc("summary", $"The {member.WireName} member.");
                writer.Line($"{member.CSharpName},");
            }
        }

        writer.Line();
        writer.XmlDoc("summary", $"Convenience accessors over the {schema.CSharpName} union.");

        using (writer.Block($"public static class {schema.CSharpName}Extensions"))
        {
            writer.XmlDoc("summary", "Returns which member carries a value.");
            writer.XmlDoc("param name=\"value\"", $"The {schema.CSharpName}.");

            using (writer.Block($"public static {kindEnum} GetKind(this {schema.CSharpName} value)"))
            {
                writer.Line("ArgumentNullException.ThrowIfNull(value);");
                writer.Line();

                var first = true;

                foreach (var member in members)
                {
                    using (writer.Block($"{(first ? "if" : "else if")} (value.{member.CSharpName} is not null)"))
                    {
                        writer.Line($"return {kindEnum}.{member.CSharpName};");
                    }

                    first = false;
                }

                writer.Line();
                writer.Line("// Unknown rather than None when the payload carried a member this contract has");
                writer.Line("// never heard of: nothing typed to hand back, but not nothing there.");

                using (writer.Block("if (value.ExtensionData is { Count: > 0 })"))
                {
                    writer.Line($"return {kindEnum}.Unknown;");
                }

                writer.Line();
                writer.Line($"return {kindEnum}.None;");
            }

            writer.Line();
            writer.XmlDoc("summary", "Returns the populated member, or null when none is set.");
            writer.XmlDoc(
                "remarks",
                "The declared return type is object because the union members share no base type. " +
                "Prefer GetKind with a switch, or the typed properties directly, when the member " +
                "is known.");
            writer.XmlDoc("param name=\"value\"", $"The {schema.CSharpName}.");

            using (writer.Block($"public static object? GetValue(this {schema.CSharpName} value)"))
            {
                writer.Line("ArgumentNullException.ThrowIfNull(value);");
                writer.Line();
                writer.Line("return");
                var first = true;

                foreach (var member in members)
                {
                    writer.Line($"    {(first ? " " : "?? ")}(object?)value.{member.CSharpName}");
                    first = false;
                }

                writer.Line("    ;");
            }
        }

        return new GeneratedFile($"Generated/Models/{schema.CSharpName}Extensions.g.cs", writer.ToString());
    }

    private static TypeContract Unwrap(TypeContract type)
        => type.Kind == TypeKind.Array && type.ElementType is not null ? type.ElementType : type;
